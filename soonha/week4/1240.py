# ─────────────────────────────────────────────────────────
# 바코드 규격: 7비트(칸)로 이루어진 패턴 하나가 숫자 0~9 중 하나에 대응됨
# 예: '0001101' → 검은/흰 칸의 폭 조합이 실제로는 숫자 '0'을 의미
# (이 매핑은 바코드 표준 규격(EAN 계열)에 정의되어 있으며, 문제에서 표로 주어짐)
# ─────────────────────────────────────────────────────────
code_to_digit = {
    '0001101': '0',
    '0011001': '1',
    '0010011': '2',
    '0111101': '3',
    '0100011': '4',
    '0110001': '5',
    '0101111': '6',
    '0111011': '7',
    '0110111': '8',
    '0001011': '9',
}

T = int(input())  # 전체 테스트케이스 개수
for test_case in range(1, T + 1):
    N, M = map(int, input().split())  # N: 이미지의 세로(행) 크기, M: 가로(열) 크기(=문자열 길이)
    
    grid = []  # 바코드 이미지를 한 줄(문자열)씩 저장할 리스트
    for _ in range(N):
        grid.append(input())  # 한 줄 전체를 '0'과 '1'로 이루어진 문자열 그대로 저장
        # '1'은 검은 칸(바코드 막대), '0'은 흰 칸(여백)을 의미한다고 가정

    # ─────────────────────────────────────────────────────
    # 바코드는 세로 방향으로는 어느 줄이나 똑같은 패턴이 찍혀 있으므로,
    # N개의 줄 중에서 굳이 다 볼 필요 없이 '1'이 하나라도 포함된 첫 줄 하나만 찾아서
    # 그 줄에서 바코드 정보를 읽으면 충분하다.
    # ─────────────────────────────────────────────────────
    code_row = None
    for row in grid:
        if '1' in row:      # 바코드 막대(검은 칸)가 있는 줄을 찾음
            code_row = row   # 그 줄을 바코드 정보를 뽑아낼 대상으로 지정
            break            # 하나 찾았으면 더 볼 필요 없으니 반복 중단

    # ─────────────────────────────────────────────────────
    # 표준 바코드(EAN-13 계열)는 숫자 8자리를 표현하고,
    # 숫자 1자리당 7비트를 사용하므로 전체 바코드 폭은 8 × 7 = 56비트다.
    # 그리고 바코드의 "마지막 비트는 항상 1(검은 칸)로 끝난다"는 규칙이 있으므로,
    # 줄 전체에서 뒤에서부터 처음 나오는 '1'의 위치를 "바코드의 끝"으로 보고
    # 거기서 56칸을 거슬러 올라가면 "바코드의 시작 위치"를 구할 수 있다.
    # ─────────────────────────────────────────────────────
    end = code_row.rfind('1')     # 문자열 뒤에서부터 처음 나오는 '1'의 인덱스 = 바코드의 마지막 칸
    start = end - 55              # 바코드는 총 56칸(=8자리×7비트)이므로, 끝에서 55칸 앞이 시작점
                                    # (end 포함 56칸: start, start+1, ..., end)
    code_bits = code_row[start:end + 1]  # 실제 바코드에 해당하는 56자리 문자열만 잘라냄

    # ─────────────────────────────────────────────────────
    # 잘라낸 56비트를 7비트씩 8묶음으로 나누어서, 각 묶음을 숫자로 디코딩한다.
    # ─────────────────────────────────────────────────────
    digits = []
    for i in range(8):  # 숫자 8자리를 하나씩 처리
        chunk = code_bits[i * 7 : i * 7 + 7]        # i번째 7비트 묶음 추출 (예: i=0이면 0~6번째 문자)
        digits.append(int(code_to_digit[chunk]))    # 매핑 테이블로 문자를 실제 숫자로 변환해서 저장

    # ─────────────────────────────────────────────────────
    # 바코드 체크섬(검증) 계산 규칙:
    # - 홀수 번째 자리(1,3,5,7번째, 0-indexed로는 0,2,4,6)의 합
    # - 짝수 번째 자리(2,4,6,8번째, 0-indexed로는 1,3,5,7)의 합
    # - "홀수자리 합 × 3 + 짝수자리 합"을 구해서 10으로 나눈 나머지가 0이면 정상 바코드
    # (이것이 실제 EAN-13 바코드의 표준 체크섬 검증 공식)
    # ─────────────────────────────────────────────────────
    odd_sum = digits[0] + digits[2] + digits[4] + digits[6]   # 0,2,4,6번 인덱스 = 1,3,5,7번째 자리
    even_sum = digits[1] + digits[3] + digits[5] + digits[7]  # 1,3,5,7번 인덱스 = 2,4,6,8번째 자리
    checksum = odd_sum * 3 + even_sum

    # ─────────────────────────────────────────────────────
    # 체크섬이 10의 배수(나머지 0)면 유효한 바코드로 판단 → 8자리 숫자의 합을 출력
    # 그렇지 않으면 위조/손상된 바코드로 판단 → 0을 출력
    # ─────────────────────────────────────────────────────
    if checksum % 10 == 0:
        print(f'#{test_case} {sum(digits)}')
    else:
        print(f'#{test_case} 0')