T = int(input())
for test_case in range(1, T + 1):
    s = input()  # 괄호로 이루어진 문자열. '(' = 막대기 시작 또는 레이저의 앞부분
                 #                        ')' = 막대기 끝 또는 레이저의 뒷부분

    cnt = 0   # 현재 "열려 있는(아직 닫히지 않은) 막대기"의 개수
              # = 스택을 쓴다면 스택에 쌓여있는 '(' 의 개수와 동일한 의미
    ans = 0   # 최종적으로 잘려서 나온 조각의 총 개수 (정답)

    pre = ''  # 바로 직전에 읽은 문자를 기억해두는 변수
              # -> "이번 ')'가 레이저(= '()')의 뒷부분인지,
              #    진짜 막대기의 끝(= '...))')인지" 구분하는 데 사용

    for c in s:
        if c == '(':
            # '(' 를 만나면: 새로운 막대기가 하나 시작된 것으로 본다
            # (실제로는 이게 나중에 레이저의 앞부분("()"의 '(')일 수도 있지만,
            #  일단 "열림" 하나가 추가된다는 사실은 동일하므로 조건 없이 증가)
            cnt += 1
        else:  # c == ')'
            # ')' 를 만나면: 가장 최근에 열렸던 '(' 하나가 닫히는 것이므로
            # 열려있는 개수를 1 감소시킨다.
            cnt -= 1

            if pre == '(':
                # 직전 문자가 '(' 였다는 것은 "()" 패턴, 즉 레이저를 의미한다.
                # (막대기라면 여는 괄호와 닫는 괄호 사이에 최소 1개 이상의
                #  다른 문자가 있어야 하는데, 레이저는 바로 붙어서 나온다)
                #
                # 레이저는 그 시점에 "현재 걸쳐 있는" 모든 막대기를 동시에 절단한다.
                # 절단되면 그 막대기들은 조각이 하나씩 늘어나므로,
                # 지금 열려있는 막대기 개수(cnt, 이미 위에서 1 감소된 상태)만큼
                # 조각 수를 더해준다.
                #
                # 주의: 여기서 cnt는 레이저 자신의 '(' ')' 쌍은
                # 이미 제외된(감소된) 상태이므로, 정확히
                # "레이저가 실제로 관통하는 막대기의 개수"가 된다.
                ans += cnt
            else:
                # 직전 문자가 ')' 였다는 것은 진짜 막대기가 끝나는 지점이다
                # (레이저가 아니라 실제 "...))" 형태로 막대기가 닫힘).
                #
                # 이 막대기는 지금까지 레이저에 몇 번 잘렸든 상관없이,
                # 마지막에 남는 "자기 자신의 마지막 한 조각"을 대표하여
                # 정확히 1개의 조각을 추가로 카운트한다.
                #
                # (중간에 레이저를 맞아 생긴 추가 조각들은 이미 위의
                #  if 분기에서 레이저를 만날 때마다 각각 카운트되었으므로,
                #  여기서는 "막대기 하나당 마지막 조각 1개"만 더해주면 된다)
                ans += 1

        pre = c  # 다음 반복을 위해 현재 문자를 "직전 문자"로 저장

    print(f'#{test_case} {ans}')